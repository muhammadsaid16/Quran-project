/**
 * باب الإتقان — Achievement Definitions
 *
 * Canonical list of unlockable achievement cards with thresholds, tiers,
 * categories, and the stat each one tracks.
 *
 * Semantic rules:
 *  - 'count' in 'memorization' counts RECITATION SESSIONS (totalRecitations),
 *    never distinct ayahs (which cap at 6,236).
 *  - Completion cards are TEXT COVERAGE (تغطية), requiring every ayah of
 *    that unit to be reviewed >= 1 time.
 *  - Accuracy cards are strict: zero omissions/substitutions/repetitions,
 *    zero uncertain words, successful phoneme alignment.
 *  - Consistency cards count LOCAL calendar days with >= 1 completed
 *    review session.
 *
 * ids are stable keys persisted in IndexedDB — rename titles freely,
 * never rename ids (that would reset users' unlocks).
 */

